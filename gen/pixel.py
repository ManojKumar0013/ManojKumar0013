def sprite_paths(rows, x, y, s, colors: dict) -> str:
    out = []
    for key in sorted({c for r in rows for c in r} - {"."}):
        col = colors.get(key)
        if not col: continue
        attr = f'class="{col[1:]}"' if col.startswith(".") else f'fill="{col}"'
        out.append(f'<path {attr} d="{_runs(rows, x, y, s, key)}"/>')
    return "".join(out)
