def text_width(s: str, scale: float) -> float:
    return (len(s) * 6 - 1) * scale if s else 0


def _runs(rows, x, y, s, on="1"):
    d = []
    for r, row in enumerate(rows):
        c = 0
        while c < len(row):
            if row[c] == on:
                e = c
                while e < len(row) and row[e] == on: e += 1
                d.append(f"M{x + c * s:g} {y + r * s:g}h{(e - c) * s:g}v{s:g}h{-(e - c) * s:g}z")
                c = e
            else:
                c += 1
    return "".join(d)


def text_path(s: str, x: float, y: float, scale: float) -> str:
    """Path data for pixel text; (x, y) is the top-left corner."""
    out = []
    for i, ch in enumerate(s.upper()):
        out.append(_runs(FONT.get(ch, FONT["?"]), x + i * 6 * scale, y, scale))
    return "".join(out)


def ptext(s, x, y, scale, cls="", anchor="start", extra=""):
    if anchor == "middle": x -= text_width(s, scale) / 2
    elif anchor == "end": x -= text_width(s, scale)
    return f'<path class="{cls}" d="{text_path(s, x, y, scale)}"{extra}/>'


