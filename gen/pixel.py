def _kotlin():
    rows = []
    for y in range(14):
        r = ""
        for x in range(14):
            inside = x < 13 - abs(y - 6.5) + 0.5 or x < 1
            r += ("K" if x + y < 13 else "O") if inside else "."
        rows.append(r)
    return rows


def _js():
    rows = [["J"] * 14 for _ in range(14)]
    glyph_j = ["001", "001", "001", "101", "111"]
    glyph_s = ["111", "100", "111", "001", "111"]
    for gy in range(5):
        for gx in range(3):
            if glyph_j[gy][gx] == "1": rows[7 + gy][5 + gx] = "k"
            if glyph_s[gy][gx] == "1": rows[7 + gy][10 + gx] = "k"
    return ["".join(r) for r in rows]


def _c():
    rows = []
    for y in range(14):
        r = ""
        for x in range(14):
            inset = max(0, 3 - y, y - 10)
            r += "H" if inset <= x <= 13 - inset else "."
        rows.append(list(r))
    letter = ["01111", "10000", "10000", "10000", "10000", "10000", "01111"]
    for gy, line in enumerate(letter):
        for gx, v in enumerate(line):
            if v == "1": rows[3 + gy + 0][4 + gx + 0] = "w"
            if v == "1" and gx == 0: rows[3 + gy][5] = "w"
    return ["".join(r) for r in rows]


